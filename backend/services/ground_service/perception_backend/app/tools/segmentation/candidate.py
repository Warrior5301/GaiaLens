"""Candidate region, cluster, and scoring data structures for Segmentation Grounding."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Optional
import numpy as np
from sac_shared_contracts.common import ArtifactRef, BBoxPx


@dataclass
class CandidateRegion:
    """Connected component extracted from thresholded probability/binary mask."""

    region_id: str
    component_id: int
    mask: np.ndarray  # 2D boolean or uint8 mask of the component
    area_pixels: int
    bbox_px: BBoxPx
    centroid: tuple[float, float]  # (cx, cy)
    mask_artifact: Optional[ArtifactRef] = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class DBSCANCluster:
    """Coherent candidate region produced by DBSCAN grouping of fragmented components."""

    cluster_id: int
    member_components: list[CandidateRegion]
    mask: np.ndarray  # Merged 2D boolean mask of all member components
    bbox_px: BBoxPx
    area_pixels: int
    centroid: tuple[float, float]  # (cx, cy)
    mask_artifact: Optional[ArtifactRef] = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class CandidateScore:
    """Scoring breakdown for a candidate mask generated for a cluster."""

    iou_with_cluster: float
    sam3_confidence: float = 0.0
    area_consistency: float = 1.0
    semantic_confidence: float = 1.0
    final_score: float = 0.0

    def compute_total_score(self, alpha_iou: float = 1.0) -> float:
        """Compute candidate score.

        Per GeoNLI paper RemoteSAM-SAM3-v2 baseline, the primary selection
        metric is the IoU between the SAM3 candidate mask and the originating DBSCAN cluster.
        """
        self.final_score = float(self.iou_with_cluster * alpha_iou)
        return self.final_score


@dataclass
class GroundingCandidate:
    """Candidate mask generated by SAM3 or RemoteSAM for a specific cluster."""

    candidate_id: str
    cluster_id: int
    mask: np.ndarray
    score: CandidateScore
    source_model: str
    bbox_px: Optional[BBoxPx] = None
    metadata: dict[str, Any] = field(default_factory=dict)
